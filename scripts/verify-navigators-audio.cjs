/* Run: node scripts/verify-navigators-audio.cjs */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('navigators-bible-plan.html','utf8');
const audio=fs.readFileSync('navigators-audio.js','utf8');
new vm.Script(audio,{filename:'navigators-audio.js'});
assert.ok(html.includes('id="audio-all"'),'Listen to all readings');
assert.ok(html.includes('id="esv-audio-frame"'),'ESV embed is present');
assert.ok(html.includes('id="audio-close"'),'Explicitly stop embedded audio');

assert.ok(html.includes('class="ot-btn ot-btn--primary audio-main"'),'Top player uses the existing primary button');
assert.ok(html.includes('class="ot-btn ot-btn--secondary esv-close"'),'Close uses the shared secondary button');
assert.ok(html.includes("listen.className='ot-btn ot-btn--secondary audio-passage'"),'Listen uses the shared secondary button');
assert.ok(audio.includes('group.insertBefore(panel,scripture)'),'Audio is placed before Scripture inside the selected passage');
assert.ok(audio.includes('home.append(panel)'),'All-readings player returns to its original location');

assert.ok(html.includes('data.audioIndex=String(i)'),'Individual listening buttons');
assert.ok(html.includes('Audio: ESV'),'Audio translation labeled ESV');
assert.ok(html.includes('World English Bible (WEB), public domain'),'Displayed text remains WEB');
assert.ok(html.includes('navigators-audio.js'),'ESV embed script loaded');
assert.ok(!html.includes('navigators-audio-manifest.js'),'Unused WEB MP3 list removed');
assert.ok(!html.includes('id="audio-pause"')&&!html.includes('id="audio-speed"'),'Do not promise unsupported ESV iframe controls');
assert.ok(html.includes("window.dispatchEvent(new CustomEvent('navigators:rendered'"),'Audio reset on render');
assert.ok(audio.includes("window.addEventListener('navigators:day-changed'"),'Audio reset on day change');
assert.ok(!/speechSynthesis|SpeechSynthesisUtterance|new Audio\(|ebible\.org\/eng-web\/audio|audio\.esv\.org/.test(audio),'No synthesized speech or direct audio files');
assert.ok(audio.includes("iframe.removeAttribute('src')"),'Closing player stops iframe playback');
assert.ok(audio.includes("encodeURIComponent(passage.replace(/ /g,'+'))"),'Matches ESV audio player URL scheme');
const sourceStart=audio.indexOf('  function normalize('),sourceEnd=audio.indexOf('  function refs(){',sourceStart);
const urlStart=audio.indexOf('  function audioURL('),urlEnd=audio.indexOf('  function buttons(){',urlStart);
assert.ok(sourceStart>=0&&sourceEnd>sourceStart&&urlStart>=0&&urlEnd>urlStart);
const methods=audio.slice(sourceStart,sourceEnd)+audio.slice(urlStart,urlEnd);
const {normalize,audioURL}=vm.runInNewContext(methods+';({normalize,audioURL})');
assert.equal(normalize('Psalms 1'),'Psalm 1');
assert.equal(normalize('Song of Songs 1'),'Song of Solomon 1');
const verseURL=audioURL(['Matthew 1:1-17']);
assert.equal(verseURL,'https://www.esv.org/audio-player/Matthew%2B1%3A1-17/');
const playlistURL=audioURL(['Matthew 1:1-17','Acts 1:1-11','Psalms 1','Genesis 1-2']);
assert.ok(playlistURL.startsWith('https://www.esv.org/audio-player/'));
assert.equal(decodeURIComponent(playlistURL.split('/').at(-2)).replaceAll('+',' '),'Matthew 1:1-17; Acts 1:1-11; Psalm 1; Genesis 1-2');
console.log('OK: supported ESV iframe URLs, exact verse ranges, four-passage selection, no synthetic narration, and safe navigation cleanup.');
